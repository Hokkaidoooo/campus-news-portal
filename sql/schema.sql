-- 仅在已选中的全新示例库执行；兼容 MySQL 5.7 / 8.0，不包含删除或预置账户。
CREATE TABLE `user` (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    uname VARCHAR(255),
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255),
    valid VARCHAR(255)
) ENGINE=InnoDB ROW_FORMAT=DYNAMIC DEFAULT CHARSET=utf8mb4;

CREATE TABLE topmenu (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    topmenuName VARCHAR(200) NOT NULL,
    topmenuContent VARCHAR(2000) NOT NULL,
    createTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE leftmenu (
    leftmenuID VARCHAR(40) NOT NULL PRIMARY KEY,
    leftmenuName VARCHAR(200) NOT NULL,
    leftmenuContent VARCHAR(2000) NOT NULL,
    createTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE news (
    newsID VARCHAR(40) NOT NULL PRIMARY KEY,
    newsName VARCHAR(200) NOT NULL,
    newsContent VARCHAR(2000) NOT NULL,
    createTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE notice (
    noticeID VARCHAR(40) NOT NULL PRIMARY KEY,
    noticeName VARCHAR(200) NOT NULL,
    noticeContent VARCHAR(2000) NOT NULL,
    createTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
